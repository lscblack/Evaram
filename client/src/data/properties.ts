const img = (id: string) =>
  `https://images.unsplash.com/${id}?auto=format&fit=crop&w=1400&q=80`

const makeImages = (propertyId: number, ids: string[]) =>
  ids.map((u, i) => ({
    id: propertyId * 100 + i,
    property_id: propertyId,
    url: img(u),
    is_cover: i === 0,
    caption: undefined,
  }))

