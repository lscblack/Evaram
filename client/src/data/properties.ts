export const getPropertyById = (id: number): Property | undefined =>
  PROPERTIES.find((p) => p.id === id)

export const getCategoryById = (id: number): PropertyCategory | undefined =>
  CATEGORIES.find((c) => c.id === id)

export const getSubCategoryById = (id: number): PropertySubCategory | undefined =>
  SUBCATEGORIES.find((s) => s.id === id)

export const getFeaturedProperties = (limit = 6): Property[] =>
  PROPERTIES.filter((p) => p.is_featured).slice(0, limit)

export const getRelatedProperties = (property: Property, limit = 3): Property[] =>
  PROPERTIES.filter(
    (p) =>
      p.id !== property.id &&
      (p.category_id === property.category_id || p.district === property.district),
  ).slice(0, limit)

